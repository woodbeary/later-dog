import { createHash } from "node:crypto";
import { it, expect } from "vitest";
import { enrolledPublication, validateCutoverBinding } from "../migration/cutover-publication.mjs";

it("publishes only the approved proposal through a held source and verifies its durable serialized acknowledgment", async () => {
  const machine = "h" + "0".repeat(24), nonce = "1".repeat(64), image = "2".repeat(64);
  const authority = { service: "dedicated-home", accountId: "fixture", machineId: machine, nonce, image, verification: "3".repeat(64), baselineManifest: "4".repeat(64), candidate: "5".repeat(64) };
  expect(() => validateCutoverBinding({ services: [{ binding: "CUTOVER", service: "other", entrypoint: "WorkFolderMigrationApi", remote: true }] }, authority)).toThrow();
  const placement = { mode: "folders", verification: authority.verification, baselineManifest: authority.baselineManifest, previous: null };
  const json = JSON.stringify(placement), revision = createHash("sha256").update(json).digest("hex");
  let installed = "", calls = 0, held = true, retired = false;
  const store = { async get(key: string) { if (key.endsWith("/reverse-enrollment")) return null; if (key.endsWith("/cutover-enrollment")) return held ? new Response(JSON.stringify({ v: 1, lease: nonce, machineId: machine, image, ...(retired ? { retired: true, retiredRevision: revision } : {}) })) : null; return installed ? new Response(installed) : null; } };
  const service = { async cutover(account: string, given: string, input: unknown) { expect([account, given, input]).toEqual(["fixture", nonce, { op: "publish", placement, precondition: { "if-none-match": "*" }, candidate: authority.candidate }]); calls++; return { phase: "committed", revision }; } };
  const request = (value = placement) => new Request("http://state.r2/work-folders/placement", { method: "PUT", headers: { "if-none-match": "*" }, body: JSON.stringify(value) });
  expect((await enrolledPublication(request(), store, "a".repeat(64), service, null))?.status).toBe(423);
  expect((await enrolledPublication(request({ ...placement, baselineManifest: "0".repeat(64) }), store, "a".repeat(64), service, authority))?.status).toBe(423);
  expect(calls).toBe(0);
  expect((await enrolledPublication(request(), store, "a".repeat(64), service, authority))?.status).toBe(423);
  installed = json;
  expect((await enrolledPublication(request(), store, "a".repeat(64), service, authority))?.status).toBe(200);
  expect(calls).toBe(2);
  retired = true;
  expect((await enrolledPublication(request(), store, "a".repeat(64), service, authority))?.status).toBe(200);
  expect(await enrolledPublication(request(), store, "a".repeat(64), service, null)).toBeNull();
  expect(calls).toBe(2);
  held = false;
  expect((await enrolledPublication(request(), store, "a".repeat(64), service, authority))?.status).toBe(423);
  expect(await enrolledPublication(request(), store, "a".repeat(64), service, null)).toBeNull();
});

it("serializes both reverse writes to one enrolled home and accepts only its verified physical recovery", async () => {
  const digest = (bytes: string) => createHash("sha256").update(bytes).digest("hex");
  const stable = "a".repeat(64), home = "homes/" + stable + "/", prefix = home + "work-folders/";
  const previousBytes = JSON.stringify({ mode: "folders" }), previous = digest(previousBytes);
  const machineId = "h" + "1".repeat(24), nonce = "3".repeat(64), baseline = "reconstructed original and later workspace", source = "current coordinator";
  const authority = { accountId: "test", machineId, nonce, direction: "reverse", previous, sourceManifest: digest(source), baselineManifest: digest(baseline), verification: "2".repeat(64), service: "test-home" };
  const service = { binding: "CUTOVER", service: authority.service, entrypoint: "WorkFolderMigrationApi", remote: true };
  expect(() => validateCutoverBinding({ services: [service] }, authority)).not.toThrow();
  expect(() => validateCutoverBinding({ services: [service] }, { ...authority, previous: "unknown" })).toThrow();
  const placement = { mode: "legacy", previous, verification: authority.verification, baselineManifest: authority.baselineManifest };
  const revision = digest(JSON.stringify(placement)), rows = new Map<string, string>();
  const held = { v: 1, lease: nonce, machineId, previous, expiresAt: Date.now() + 60000 };
  rows.set(prefix + "reverse-enrollment", JSON.stringify(held));
  rows.set(prefix + "placements/" + previous, previousBytes);
  const store = { async get(key: string) { return rows.has(key) ? new Response(rows.get(key)) : null; } };
  const calls: unknown[] = [];
  const api = { async reverse(account: string, lease: string, input: { op: string }) { expect([account, lease]).toEqual([authority.accountId, nonce]); calls.push(input); return { phase: input.op === "project" ? "projected" : "committed", revision }; } };
  const request = (op: string, proposal = placement) => new Request("http://state.r2/work-folders/" + op, { method: op === "placement" ? "PUT" : "POST", headers: { "if-match": '"etag"' }, body: JSON.stringify(op === "placement" ? proposal : { placement: proposal, source: authority.sourceManifest }) });
  const check = (op: string, who: typeof authority | null = authority) => enrolledPublication(request(op), store, stable, api, who);
  expect((await check("project-legacy"))?.status).toBe(423);
  const origin = "5".repeat(64), sourceLeaseSha256 = digest(origin), previousImage = "7".repeat(64);
  const sealed = { ...authority, sourceLeaseSha256, previousImage };
  expect(() => validateCutoverBinding({ services: [service] }, { ...authority, previousImage })).toThrow();
  expect(() => validateCutoverBinding({ services: [service] }, sealed)).not.toThrow();
  rows.set(prefix + "cutover-enrollment", JSON.stringify({ v: 1, machineId, lease: origin }));
  rows.set(prefix + "reverse-enrollment", JSON.stringify({ ...held, sourceLeaseSha256, previousImage }));
  expect((await check("placement", null))?.status).toBe(423);
  expect((await check("project-legacy"))?.status).toBe(423);
  expect((await check("project-legacy", { ...sealed, previousImage: origin } as typeof sealed))?.status).toBe(423);
  rows.set(prefix + "cutover-enrollment", JSON.stringify({ v: 1, machineId, lease: "6".repeat(64) }));
  expect((await check("project-legacy", sealed))?.status).toBe(423);
  rows.set(prefix + "cutover-enrollment", JSON.stringify({ v: 1, machineId, lease: origin }));
  rows.delete(prefix + "placements/" + previous);
  expect((await check("project-legacy", sealed))?.status).toBe(423);
  expect(calls).toHaveLength(0);
  rows.set(prefix + "placements/" + previous, previousBytes);
  rows.set(home + "manifest.json", baseline);
  expect((await check("project-legacy", sealed))?.status).toBe(200);
  expect(calls.pop()).toEqual({ op: "project", source: authority.sourceManifest, placement, etag: '"etag"' });
  rows.set(prefix + "reverse-enrollment", JSON.stringify(held));
  rows.set(prefix + "cutover-enrollment", JSON.stringify({ v: 1, machineId, retired: true, retiredRevision: previous }));
  expect((await check("placement", null))?.status).toBe(423);
  expect((await check("project-legacy", { ...authority, nonce: "9".repeat(64) }))?.status).toBe(423);
  expect((await enrolledPublication(request("placement", { ...placement, previous: revision }), store, stable, api, authority))?.status).toBe(423);
  expect(calls).toHaveLength(0);
  rows.set(home + "manifest.json", source);
  expect((await check("project-legacy"))?.status).toBe(423);
  rows.set(home + "manifest.json", baseline);
  expect(await (await check("project-legacy"))?.json()).toEqual({ revision: authority.baselineManifest });
  expect(calls.at(-1)).toEqual({ op: "project", source: authority.sourceManifest, placement, etag: '"etag"' });
  expect((await check("placement"))?.status).toBe(423);
  rows.set(prefix + "placement", JSON.stringify(placement));
  expect(await (await check("placement"))?.json()).toEqual({ revision });
  expect(calls.at(-1)).toEqual({ op: "publish", placement, precondition: { "if-match": '"etag"' } });
  rows.set(prefix + "reverse-enrollment", JSON.stringify({ ...held, completedRevision: revision }));
  rows.set(prefix + "placements/" + revision, JSON.stringify(placement));
  rows.set(home + "manifest.json", "subsequent real work");
  const completedCalls = calls.length;
  expect((await check("placement"))?.status).toBe(423);
  rows.set(prefix + "legacy-manifests/" + authority.baselineManifest, baseline);
  expect((await check("placement"))?.status).toBe(200);
  expect(calls).toHaveLength(completedCalls);
  rows.set(prefix + "placement", "another active migration");
  expect((await check("placement"))?.status).toBe(423);
});
