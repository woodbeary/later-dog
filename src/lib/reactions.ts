export const EMOJI_CATALOG: ReadonlyArray<EmojiEntry> = CATALOG.map(([emoji, words]) => ({ emoji, words }));

export function searchEmoji(query: string, catalog: ReadonlyArray<EmojiEntry> = EMOJI_CATALOG): EmojiEntry[] {
  const terms = query.trim().toLowerCase().split(/\s+/).filter(Boolean);
  if (!terms.length) return [...catalog];
  return catalog.filter((entry) => terms.every((term) => entry.emoji === term || entry.words.split(" ").some((word) => word.startsWith(term))));
}

export type Reaction = { emoji: string; by: string };

export const MY_REACTION = "user";

export interface ReactionSummary {
  emoji: string;
  count: number;
  mine: boolean;
  by: string[];
}

export function reactionSummary(reactions: ReadonlyArray<Reaction> | undefined, me = MY_REACTION): ReactionSummary[] {
  const order: string[] = [];
  const groups = new Map<string, string[]>();
  for (const reaction of reactions ?? []) {
    const known = groups.get(reaction.emoji);
    if (!known) {
      order.push(reaction.emoji);
      groups.set(reaction.emoji, [reaction.by]);
    } else if (!known.includes(reaction.by)) known.push(reaction.by);
  }
  return order.map((emoji) => {
    const by = groups.get(emoji)!;
    return { emoji, count: by.length, mine: by.includes(me), by };
  });
}

export function toggledReactions(reactions: ReadonlyArray<Reaction> | undefined, emoji: string, by = MY_REACTION): Reaction[] | undefined {
  const current = reactions ?? [];
  const at = current.findIndex((reaction) => reaction.emoji === emoji && reaction.by === by);
  const next = at >= 0 ? current.filter((_, index) => index !== at) : [...current, { emoji, by }];
  return next.length ? next : undefined;
}

export function myReactions(reactions: ReadonlyArray<Reaction> | undefined, me = MY_REACTION): string[] {
  return (reactions ?? []).filter((reaction) => reaction.by === me).map((reaction) => reaction.emoji);
}
